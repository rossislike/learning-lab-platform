function execute(command, args, options = {}) {
  return spawnSync(command, args, { encoding: "utf8", stdio: options.capture ? "pipe" : "inherit" })
}

function parseFlags(values) {
  const parsed = new Map()
  for (const value of values) {
    const match = /^--([^=]+)=(.*)$/.exec(value)
    if (!match || !knownFlags.has(match[1]) || parsed.has(match[1])) return null
    parsed.set(match[1], match[2])
  }
  return parsed
}

function terraformArgs(environment, action, extra = []) {
  return [`-chdir=infra/aws/environments/${environment}`, action, `-var-file=${environment}.tfvars`, ...extra]
}

function resultText(result) { return result.status === 0 ? result.stdout.trim() : null }
function jsonResult(run, command, args) {
  const text = resultText(run(command, args, { capture: true }))
  if (text === null) return null
  try { return JSON.parse(text) } catch { return null }
}

function atomicWrite(path, contents, fs) {
  const temporary = `${path}.tmp-${process.pid}`
  fs.writeFileSync(temporary, contents, { flag: "wx", mode: 0o600 })
  fs.renameSync(temporary, path)
}

function sha256(path, fs) { return createHash("sha256").update(fs.readFileSync(path)).digest("hex") }

function usage() {
  console.error("usage: npm run infra:teardown -- <audit|prepare|plan|apply|abort|cleanup> <staging|production> --account=<12-digit-id> [--confirm=<phrase>]")
}

function checkAccount(account, run) {
  if (!/^\d{12}$/.test(account ?? "")) return false
  return resultText(run("aws", ["sts", "get-caller-identity", "--query", "Account", "--output", "text"], { capture: true })) === account
}

function readOwner(path, fs) {
  if (!fs.existsSync(path)) return null
  try { return JSON.parse(fs.readFileSync(path, "utf8")) } catch { return null }
}

function owns(owner, environment, account) {
  return [1, 2].includes(owner?.version) && owner.environment === environment && owner.account === account
}

function regionFromEcsClusterArn(arn) {
  if (typeof arn !== "string") return null
  const match = /^arn:(aws|aws-us-gov|aws-cn):ecs:([a-z]{2}(?:-[a-z0-9]+)+-\d+):(\d{12}):cluster\/[A-Za-z0-9_-]+$/.exec(arn)
  if (!match) return null
  const [, partition, region] = match
  if (partition === "aws-cn" && !region.startsWith("cn-")) return null
  if (partition === "aws-us-gov" && !region.startsWith("us-gov-")) return null
  if (partition === "aws" && (region.startsWith("cn-") || region.startsWith("us-gov-"))) return null
  return region
}

function flattenStateResources(module, resources = []) {
  if (!module) return resources
  for (const resource of module.resources ?? []) {
    if (resource.mode === "managed") resources.push(resource)
  }
  for (const child of module.child_modules ?? []) flattenStateResources(child, resources)
  return resources
}

function stateResources(environment, run) {
  const state = jsonResult(run, "terraform", [`-chdir=infra/aws/environments/${environment}`, "show", "-json"])
  if (!state || typeof state !== "object") return null
  return flattenStateResources(state.values?.root_module)
}

function arnRegionAndAccount(arn, service) {
  if (typeof arn !== "string") return null
  const match = new RegExp(`^arn:(aws|aws-us-gov|aws-cn):${service}:([a-z]{2}(?:-[a-z0-9]+)+-\\d+):(\\d{12}):`).exec(arn)
  if (!match) return null
  return { region: match[2], account: match[3] }
}

function resourceIdentity(spec, resource) {
  if (!resource?.values) return null
  if (["ecs", "alb", "ecr"].includes(spec.kind)) return resource.values.arn ?? null
  if (spec.kind === "s3") return resource.values.bucket ?? resource.values.id ?? null
  return null
}

function inventoryFromState(environment, account, run) {
  const resources = stateResources(environment, run)
  if (!resources) return { error: "could not read the Terraform state snapshot" }
  const byAddress = new Map(resources.map((resource) => [resource.address, resource]))
  const inventory = { region: null, resources: {} }
  for (const spec of monitoredResources) {
    const resource = byAddress.get(spec.address)
    if (!resource) return { error: `required Terraform resource is missing before prepare: ${spec.address}` }
    const identity = resourceIdentity(spec, resource)
    if (typeof identity !== "string" || !identity) return { error: `could not identify ${spec.address} from Terraform state` }
    inventory.resources[spec.key] = { address: spec.address, identity }
    if (["ecs", "alb", "ecr"].includes(spec.kind)) {
      const arn = arnRegionAndAccount(identity, spec.kind === "alb" ? "elasticloadbalancing" : spec.kind)
      if (!arn || arn.account !== account) return { error: `${spec.address} is not owned by account ${account}` }
      if (inventory.region && inventory.region !== arn.region) return { error: "monitored resources span multiple AWS regions" }
      inventory.region = arn.region
    }
  }
  const clusterRegion = regionFromEcsClusterArn(inventory.resources.ecsCluster.identity)
  if (!inventory.region || clusterRegion !== inventory.region) return { error: "could not establish one trusted AWS region from Terraform state" }
  return { inventory }
}

function currentMonitoredResources(environment, owner, run) {
  if (owner?.version !== 2 || !owner.inventory?.region || !owner.inventory?.resources) {
    return { error: "teardown ownership lacks the prepared resource inventory; abort and prepare again" }
  }
  const resources = stateResources(environment, run)
  if (!resources) return { error: "could not read the Terraform state snapshot" }
  const byAddress = new Map(resources.map((resource) => [resource.address, resource]))
  const current = new Map()
  for (const spec of monitoredResources) {
    const resource = byAddress.get(spec.address)
    if (!resource) continue
    const saved = owner.inventory.resources[spec.key]
    const identity = resourceIdentity(spec, resource)
    if (!saved || saved.address !== spec.address || !identity || identity !== saved.identity) {
      return { error: `Terraform resource identity changed after prepare: ${spec.address}` }
    }
    current.set(spec.key, { ...spec, identity })
  }
  return { current, all: resources }
}

function albLoggingEnabled(albArn, region, run) {
  const result = jsonResult(run, "aws", [
    "elbv2", "describe-load-balancer-attributes", "--region", region,
    "--load-balancer-arn", albArn, "--output", "json",
  ])
  if (!result) return null
  return result.Attributes?.find((attribute) => attribute.Key === "access_logs.s3.enabled")?.Value === "true"
}

function preflight(environment, account, owner, run, now, drainMs) {
  const inspected = currentMonitoredResources(environment, owner, run)
  if (inspected.error) return inspected.error
  const { current } = inspected
  const region = owner.inventory.region
  if (current.has("ecsCluster")) {
    const cluster = current.get("ecsCluster").identity
    const arn = arnRegionAndAccount(cluster, "ecs")
    if (!arn || arn.account !== account || arn.region !== region) return "ECS cluster identity is outside the prepared account or region"
    for (const status of ["RUNNING", "PENDING"]) {
      const tasks = jsonResult(run, "aws", ["ecs", "list-tasks", "--region", region, "--cluster", cluster, "--desired-status", status, "--output", "json"])
      if (!tasks) return `could not inspect ${status.toLowerCase()} ECS tasks`
      if ((tasks.taskArns ?? []).length) return `ECS has ${status.toLowerCase()} tasks`
    }
    const services = jsonResult(run, "aws", ["ecs", "list-services", "--region", region, "--cluster", cluster, "--output", "json"])
    if (!services) return "could not inspect ECS services"
    if ((services.serviceArns ?? []).length) {
      const described = jsonResult(run, "aws", ["ecs", "describe-services", "--region", region, "--cluster", cluster, "--services", ...services.serviceArns, "--output", "json"])
      if (!described) return "could not describe ECS services"
      if ((described.services ?? []).some((service) => service.desiredCount || service.runningCount || service.pendingCount)) return "ECS services are not scaled to zero"
    }
  }
  if (current.has("publicAlb")) {
    const enabled = albLoggingEnabled(current.get("publicAlb").identity, region, run)
    if (enabled === null) return "could not verify public ALB access logging"
    if (enabled) return "public ALB access logging is still enabled"
  }
  if (current.has("albAccessLogBucket")) {
    const disabledAt = Date.parse(owner.albAccessLoggingDisabledAt ?? "")
    if (!Number.isFinite(disabledAt)) return "ALB access-log disable time is missing"
    if (now() - disabledAt < drainMs) return "ALB access-log delivery drain window has not elapsed"
  }
  for (const key of ["artifactBucket", "checkpointBucket", "albAccessLogBucket"]) {
    const resource = current.get(key)
    if (!resource) continue
    const contents = jsonResult(run, "aws", ["s3api", "list-object-versions", "--region", region, "--bucket", resource.identity, "--output", "json"])
    if (!contents) return `could not inspect ${key}`
    if ((contents.Versions ?? []).length || (contents.DeleteMarkers ?? []).length) return `${key} is not empty`
  }
  for (const key of ["runnerRepository", "dispatcherRepository", "gatewayRepository", "egressProxyRepository"]) {
    const resource = current.get(key)
    if (!resource) continue
    const repositoryName = resource.identity.slice(resource.identity.indexOf("repository/") + "repository/".length)
    if (!repositoryName) return `could not identify ${key}`
    const images = jsonResult(run, "aws", ["ecr", "describe-images", "--region", region, "--repository-name", repositoryName, "--output", "json"])
    if (!images) return `could not inspect ${key}`
    if ((images.imageDetails ?? []).length) return `${key} is not empty`
  }
  return null
}

function restore(environment, owner, run, paths, fs) {
  if (fs.existsSync(paths.override)) fs.rmSync(paths.override)
  const result = run("terraform", terraformArgs(environment, "apply", [...targets, "-auto-approve"]))
  if ((result.status ?? 1) !== 0) {
    atomicWrite(paths.override, teardownOverride, fs)
    console.error("blocked: restoring normal load balancer protections failed; teardown ownership remains active")
    return result.status ?? 1
  }
  const inspected = owner?.version === 2 ? currentMonitoredResources(environment, owner, run) : null
  if (inspected?.error || inspected?.current.has("publicAlb")) {
    const enabled = inspected?.error ? null : albLoggingEnabled(owner.inventory.resources.publicAlb.identity, owner.inventory.region, run)
    if (enabled !== true) {
      atomicWrite(paths.override, teardownOverride, fs)
      console.error("blocked: restored public ALB access logging could not be verified; teardown ownership remains active")
      return 1
    }
  }
  fs.rmSync(paths.manifest, { force: true })
  fs.rmSync(paths.plan, { force: true })
  fs.rmSync(paths.planMeta, { force: true })
  return 0
}

function removeTeardownFiles(paths, fs) {
  fs.rmSync(paths.override, { force: true })
  fs.rmSync(paths.manifest, { force: true })
  fs.rmSync(paths.plan, { force: true })
  fs.rmSync(paths.planMeta, { force: true })
}

export function runTeardown(args = process.argv.slice(2), deps = {}) {
  const [action, environment, ...rawFlags] = args
  const flags = parseFlags(rawFlags)
  if (!actions.has(action) || !environments.has(environment) || !flags) { usage(); return 2 }
  const run = deps.execute ?? execute
  const fs = deps.fs ?? { existsSync, readFileSync, renameSync, rmSync, writeFileSync }
  const now = deps.now ?? Date.now
  const drainMs = deps.albLogDrainMs ?? defaultAlbLogDrainMs
  const root = deps.rootPath ?? process.cwd()
  const account = flags.get("account")
  if (!checkAccount(account, run)) { console.error("blocked: active AWS account does not match a valid --account"); return 1 }
  const environmentDir = join(root, `infra/aws/environments/${environment}`)
  const paths = {
    override: join(root, relativeOverride), manifest: join(root, relativeManifest),
    plan: join(environmentDir, `.terraform/${environment}-destroy.tfplan`),
    planMeta: join(environmentDir, `.terraform/${environment}-destroy.tfplan.json`),
  }
  const owner = readOwner(paths.manifest, fs)
  if (action === "audit") {
    const state = run("terraform", [`-chdir=infra/aws/environments/${environment}`, "state", "list"], { capture: true })
    if (state.status !== 0) return state.status ?? 1
    console.log(JSON.stringify({ account, environment, managedResources: state.stdout.trim() ? state.stdout.trim().split("\n").length : 0, owner }, null, 2))
    return 0
  }
  if (action === "prepare") {
    if (flags.get("confirm") !== `prepare teardown ${environment} in ${account}`) return 1
    if (owner || fs.existsSync(paths.override)) { console.error("blocked: a teardown is already active or has inconsistent metadata"); return 1 }
    const lock = { version: 2, environment, account }
    try {
      fs.writeFileSync(paths.manifest, JSON.stringify(lock, null, 2) + "\n", { flag: "wx", mode: 0o600 })
    } catch {
      console.error("blocked: another teardown acquired the shared ownership lock")
      return 1
    }
    const captured = inventoryFromState(environment, account, run)
    if (captured.error) {
      fs.rmSync(paths.manifest, { force: true })
      console.error(`blocked: ${captured.error}`)
      return 1
    }
    const preparedOwner = { ...lock, inventory: captured.inventory }
    atomicWrite(paths.manifest, JSON.stringify(preparedOwner, null, 2) + "\n", fs)
    try { atomicWrite(paths.override, teardownOverride, fs) } catch (error) { fs.rmSync(paths.manifest, { force: true }); throw error }
    const result = run("terraform", terraformArgs(environment, "apply", [...targets, "-auto-approve"]))
    if ((result.status ?? 1) !== 0) {
      console.error("prepare failed; attempting to restore normal deletion protection")
      const restoreStatus = restore(environment, preparedOwner, run, paths, fs)
      return restoreStatus === 0 ? (result.status ?? 1) : restoreStatus
    }
    const logging = albLoggingEnabled(preparedOwner.inventory.resources.publicAlb.identity, preparedOwner.inventory.region, run)
    if (logging !== false) {
      console.error("prepare failed: public ALB access logging was not verifiably disabled; attempting to restore normal protections")
      const restoreStatus = restore(environment, preparedOwner, run, paths, fs)
      return restoreStatus === 0 ? 1 : restoreStatus
    }
    atomicWrite(paths.manifest, JSON.stringify({
      ...preparedOwner,
      albAccessLoggingDisabledAt: new Date(now()).toISOString(),
    }, null, 2) + "\n", fs)
    return 0
  }
  if (!owns(owner, environment, account)) {
    console.error("blocked: teardown ownership does not match this environment and account")
    return 1
  }
  if (action === "abort") {
    if (flags.get("confirm") !== `abort teardown ${environment} in ${account}`) return 1
    if (fs.existsSync(paths.override) && fs.readFileSync(paths.override, "utf8") !== teardownOverride) {
      console.error("blocked: teardown override has unexpected content")
      return 1
    }
    if (!fs.existsSync(paths.override) && owner.version === 2 && !owner.inventory) {
      removeTeardownFiles(paths, fs)
      return 0
    }
    if (!fs.existsSync(paths.override)) {
      const state = run("terraform", [`-chdir=infra/aws/environments/${environment}`, "state", "list"], { capture: true })
      if (state.status !== 0) return state.status ?? 1
      if (!state.stdout.trim()) { removeTeardownFiles(paths, fs); return 0 }
    }
    if (owner.version === 2) {
      const inspected = currentMonitoredResources(environment, owner, run)
      if (inspected.error) { console.error(`blocked: ${inspected.error}`); return 1 }
      const missing = Object.values(owner.inventory.resources).some(({ address }) => !inspected.all.some((resource) => resource.address === address))
      if (missing) {
        console.error("blocked: partial destroy detected; continue with guarded plan and apply instead of recreating resources")
        return 1
      }
    }
    return restore(environment, owner, run, paths, fs)
  }
  if (action === "cleanup") {
    if (fs.existsSync(paths.override) && fs.readFileSync(paths.override, "utf8") !== teardownOverride) {
      console.error("blocked: teardown override has unexpected content")
      return 1
    }
    const state = run("terraform", [`-chdir=infra/aws/environments/${environment}`, "state", "list"], { capture: true })
    if (state.status !== 0) return state.status ?? 1
    if (state.stdout.trim()) { console.error("blocked: Terraform still manages environment resources; continue guarded teardown or abort before destruction starts"); return 1 }
    removeTeardownFiles(paths, fs)
    return 0
  }
  if (!fs.existsSync(paths.override) || fs.readFileSync(paths.override, "utf8") !== teardownOverride) {
    console.error("blocked: teardown override is missing or has unexpected content; use abort to recover an interrupted prepare")
    return 1
  }
  if (action === "plan") {
    if (flags.get("confirm") !== `plan teardown ${environment} in ${account}`) return 1
    fs.rmSync(paths.plan, { force: true }); fs.rmSync(paths.planMeta, { force: true })
    const blocked = preflight(environment, account, owner, run, now, drainMs)
    if (blocked) { console.error(`blocked: ${blocked}`); return 1 }
    const result = run("terraform", terraformArgs(environment, "plan", ["-destroy", `-out=.terraform/${environment}-destroy.tfplan`]))
    if ((result.status ?? 1) !== 0) {
      fs.rmSync(paths.plan, { force: true }); fs.rmSync(paths.planMeta, { force: true })
      return result.status ?? 1
    }
    atomicWrite(paths.planMeta, JSON.stringify({ version: 1, environment, account, sha256: sha256(paths.plan, fs) }, null, 2) + "\n", fs)
    return 0
  }
  if (action === "apply") {
    if (flags.get("confirm") !== `destroy ${environment} in ${account}`) return 1
    const metadata = readOwner(paths.planMeta, fs)
    if (!fs.existsSync(paths.plan) || !owns(metadata, environment, account) || metadata.sha256 !== sha256(paths.plan, fs)) {
      console.error("blocked: destroy plan is missing, tampered, or owned by another environment/account")
      return 1
    }
    const blocked = preflight(environment, account, owner, run, now, drainMs)
    if (blocked) { console.error(`blocked: ${blocked}`); return 1 }
    return run("terraform", [`-chdir=infra/aws/environments/${environment}`, "apply", `.terraform/${environment}-destroy.tfplan`]).status ?? 1
  }
  return 2
}

if (process.argv[1] === fileURLToPath(import.meta.url)) process.exitCode = runTeardown()
