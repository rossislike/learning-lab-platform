// Validates scenarios/ and writes:
//   convex/scenarioSeedData.ts        areas + scenarios (markdown inlined)
//   build/scenarios/<slug>.<sha256>.tar learner bundles (solutions, solve scripts excluded)
//   build/scenarios/index.json        slug → bundle digest, size, key
//
// Usage:
//   npm run scenarios:import              write everything
//   npm run scenarios:check               validate and confirm the seed file is current
//   node scripts/import-scenarios.mjs --no-bundle

import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { relative, resolve } from "node:path";
import { buildScenarioBundle } from "./scenario-bundle.mjs";
import { CatalogError, loadCatalog, projectRoot, toSeedRecord } from "./scenario-catalog.mjs";

const seedPath = resolve(projectRoot, "convex/scenarioSeedData.ts");
const bundleRoot = resolve(projectRoot, "build/scenarios");

function renderSeedData(areas, scenarios) {
  return [
    "// Generated by `npm run scenarios:import`. Do not edit by hand.",
    "",
    `export const areaSeedData = ${JSON.stringify(areas, null, 2)} as const;`,
    "",
    `export const scenarioSeedData = ${JSON.stringify(scenarios, null, 2)} as const;`,
    "",
  ].join("\n");
}

async function main(argv) {
  const checkOnly = argv.includes("--check");
  const skipBundles = argv.includes("--no-bundle") || checkOnly;
  const unknown = argv.filter((arg) => !["--check", "--no-bundle"].includes(arg));
  if (unknown.length > 0) throw new Error(`[scenario-import] unknown arguments: ${unknown.join(" ")}`);

  const { areas, scenarios } = await loadCatalog();
  const areasBySlug = new Map(areas.map((area) => [area.slug, area]));
  const records = scenarios.map((scenario) => toSeedRecord(scenario, areasBySlug));
  const output = renderSeedData(areas, records);

  if (checkOnly) {
    const existing = await readFile(seedPath, "utf8").catch(() => "");
    if (existing !== output) {
      throw new Error(
        `[scenario-import] ${relative(projectRoot, seedPath)} is out of date. Run npm run scenarios:import`,
      );
    }
  } else {
    await writeFile(seedPath, output);
  }

  const index = {};
  if (!skipBundles) {
    await rm(bundleRoot, { recursive: true, force: true });
    await mkdir(bundleRoot, { recursive: true });
    for (const scenario of scenarios) {
      const bundle = await buildScenarioBundle(scenario.scenarioDir, scenario.manifest);
      const fileName = `${scenario.manifest.slug}.${bundle.sha256}.tar`;
      await writeFile(resolve(bundleRoot, fileName), bundle.tar);
      index[scenario.manifest.slug] = {
        area: scenario.manifest.area,
        kind: scenario.manifest.kind,
        sha256: bundle.sha256,
        sizeBytes: bundle.sizeBytes,
        key: bundle.key,
        file: fileName,
        entries: bundle.entryPaths.length,
      };
    }
    await writeFile(resolve(bundleRoot, "index.json"), `${JSON.stringify(index, null, 2)}\n`);
  }

  for (const scenario of scenarios) {
    const { slug, area, kind } = scenario.manifest;
    const bundleNote = index[slug] ? ` bundle ${index[slug].sha256.slice(0, 12)} (${index[slug].sizeBytes} B)` : "";
    console.log(`[scenario-import] ${area}/${slug} (${kind}, ${scenario.steps.length} steps)${bundleNote}`);
  }
  console.log(
    checkOnly
      ? `[scenario-import] checked ${relative(projectRoot, seedPath)}`
      : `[scenario-import] wrote ${relative(projectRoot, seedPath)}${skipBundles ? "" : ` and ${relative(projectRoot, bundleRoot)}/`}`,
  );
}

try {
  await main(process.argv.slice(2));
} catch (error) {
  console.error(error instanceof CatalogError ? error.message : error);
  process.exitCode = 1;
}
