import { createHash, randomUUID } from "node:crypto"
import { existsSync, readFileSync, renameSync, rmSync, writeFileSync } from "node:fs"
import { join } from "node:path"

import { validateCanonicalTerraformRoots } from "./aws-terraform-operations.mjs"

const accountSecurityDir = "infra/aws/account-security"
const lifecycleRelativePath = `${accountSecurityDir}/zz-learning-lab-alarms.auto.tfvars.json`
const overrideRelativePath = `${accountSecurityDir}/learning_lab_alarms_teardown_override.tf`
const alarmAddressPrefix = "aws_cloudwatch_metric_alarm.security["
const alarmNamePrefix = "learning-lab-platform-"

export const learningLabAlarmKeys = Object.freeze([
  "cloudtrail-changes",
  "cloudwatch-alerting-changes",
  "console-login-without-mfa",
  "edge-security-logging-changes",
  "guardduty-configuration-changes",
  "iam-identity-and-credential-changes",
  "iam-policy-changes",
  "kms-key-disable-or-delete",
  "notification-routing-changes",
  "root-account-usage",
  "security-group-changes",
  "unauthorized-api-calls",
])

export const sharedAlarmTeardownOverride = `# Generated by the guarded shared-alarm lifecycle workflow. Do not commit.
resource "aws_cloudwatch_metric_alarm" "security" {
  lifecycle {
    prevent_destroy = false
  }
}
`

function resultStatus(result) {
  return typeof result === "number" ? result : result?.status ?? 1
}

function resultText(result) {
  return resultStatus(result) === 0 && typeof result?.stdout === "string" ? result.stdout.trim() : null
}

function jsonResult(run, command, args) {
  const output = resultText(run(command, args, { capture: true }))
  if (output === null) return null
  try { return JSON.parse(output) } catch { return null }
}

function readJsonFile(path, fs) {
  try { return JSON.parse(fs.readFileSync(path, "utf8")) } catch { return null }
}

function atomicWrite(path, contents, fs) {
  const temporary = `${path}.tmp-${process.pid}`
  fs.writeFileSync(temporary, contents, { flag: "wx", mode: 0o600 })
  fs.renameSync(temporary, path)
}

function sha256(path, fs) {
  return createHash("sha256").update(fs.readFileSync(path)).digest("hex")
}

function expectedAddress(key) {
  return `aws_cloudwatch_metric_alarm.security["${key}"]`
}

function expectedAlarmName(key) {
  return `${alarmNamePrefix}${key}`
}

function lifecycleContents(enabled) {
  return `${JSON.stringify({ enable_learning_lab_alarms: enabled }, null, 2)}\n`
}

export function readSharedAlarmLifecycle(rootPath = process.cwd(), fs = { readFileSync }) {
  try {
    const value = JSON.parse(fs.readFileSync(join(rootPath, lifecycleRelativePath), "utf8"))
    if (Object.keys(value).length !== 1 || typeof value.enable_learning_lab_alarms !== "boolean") return null
    return value.enable_learning_lab_alarms
  } catch { return null }
}

export function writeSharedAlarmLifecycle(enabled, rootPath = process.cwd(), fs = { renameSync, writeFileSync }) {
  atomicWrite(join(rootPath, lifecycleRelativePath), lifecycleContents(enabled), fs)
}

function stateAddresses(run) {
  const state = resultText(run("terraform", [`-chdir=${accountSecurityDir}`, "state", "list"], { capture: true }))
  return state === null ? null : state.split("\n").filter(Boolean)
}

function alarmStateIsExpected(addresses) {
  const expected = new Set(learningLabAlarmKeys.map(expectedAddress))
  return addresses.every((address) => !address.startsWith(alarmAddressPrefix) || expected.has(address))
}

function planIsScoped(plan, enabled, account) {
  if (!Array.isArray(plan?.resource_changes)) return false
  if (plan.variables?.expected_aws_account_id?.value !== account) return false
  const region = plan.variables?.aws_region?.value
  if (typeof region !== "string" || !/^[a-z]{2}(?:-[a-z0-9]+)+-\d+$/.test(region)) return false
  const expected = new Set(learningLabAlarmKeys)
  for (const resource of plan.resource_changes) {
    const actions = resource.change?.actions ?? []
    if (!actions.some((action) => !["no-op", "read"].includes(action))) continue
    const key = resource.index
    if (
      typeof key !== "string" || !expected.has(key) ||
      resource.address !== expectedAddress(key) ||
      resource.type !== "aws_cloudwatch_metric_alarm" ||
      resource.name !== "security"
    ) return false
    if (enabled) {
      const action = actions.join(",")
      if (!["create", "update"].includes(action) || resource.change?.after?.alarm_name !== expectedAlarmName(key)) return false
      if (resource.change?.before && resource.change.before.alarm_name !== expectedAlarmName(key)) return false
    } else if (
      actions.length !== 1 || actions[0] !== "delete" ||
      resource.change?.before?.alarm_name !== expectedAlarmName(key)
    ) return false
  }
  return true
}

function environmentStatesEmpty(run) {
  for (const environment of ["staging", "production"]) {
    const state = resultText(run("terraform", [`-chdir=infra/aws/environments/${environment}`, "state", "list"], { capture: true }))
    if (state === null || state) return false
  }
  return true
}

function liveAlarmsMatch(run, region, enabled) {
  const live = jsonResult(run, "aws", [
    "cloudwatch", "describe-alarms", "--region", region,
    "--alarm-name-prefix", alarmNamePrefix, "--max-items", "1000", "--output", "json",
  ])
  if (!live || (live.CompositeAlarms ?? []).length) return false
  const names = (live.MetricAlarms ?? []).map((alarm) => alarm.AlarmName).sort()
  const expected = enabled ? learningLabAlarmKeys.map(expectedAlarmName).sort() : []
  return names.length === expected.length && names.every((name, index) => name === expected[index])
}

function fail(message) {
  console.error(`blocked: ${message}`)
  return 1
}

export function reconcileSharedAlarms(options = {}) {
  const enabled = options.enabled
  const account = options.account
  const run = options.execute
  const rootPath = options.rootPath ?? process.cwd()
  const fs = options.fs ?? { existsSync, readFileSync, renameSync, rmSync, writeFileSync }
  const verifyLock = options.verifyOperationLock
  const planId = options.planId ?? randomUUID()
  if (typeof enabled !== "boolean" || !/^\d{12}$/.test(account ?? "") || typeof run !== "function") return fail("shared alarm lifecycle arguments are invalid")
  if (!/^[0-9a-f-]{8,64}$/i.test(planId)) return fail("shared alarm plan owner is invalid")
  if (typeof verifyLock !== "function" || !verifyLock()) return fail("shared hosted operation lock is not held")

  const validationOptions = { rootPath, fs, execute: run, account, registry: options.backendRegistry }
  const validateBackends = options.validateBackends ?? validateCanonicalTerraformRoots
  const validated = validateBackends(["accountSecurity", "staging", "production"], validationOptions)
  if (!validated.ok) return fail(validated.error)
  if (!enabled && !environmentStatesEmpty(run)) return fail("hosted environment Terraform state is not empty")

  const originalLifecycle = readSharedAlarmLifecycle(rootPath, fs)
  if (originalLifecycle === null) return fail("tracked shared alarm lifecycle file is invalid")
  const overridePath = join(rootPath, overrideRelativePath)
  if (fs.existsSync(overridePath)) return fail("a shared alarm teardown override already exists")
  const planName = `shared-alarms-${enabled ? "enable" : "disable"}-${planId}.tfplan`
  const planPath = join(rootPath, accountSecurityDir, ".terraform", planName)
  const metadataPath = `${planPath}.json`
  let applyStarted = false
  let status = 1
  try {
    writeSharedAlarmLifecycle(enabled, rootPath, fs)
    if (!enabled) atomicWrite(overridePath, sharedAlarmTeardownOverride, fs)

    const before = stateAddresses(run)
    if (!before || !alarmStateIsExpected(before)) return fail("Terraform state contains an unexpected shared alarm instance")
    const planResult = run("terraform", [
      `-chdir=${accountSecurityDir}`,
      "plan",
      "-input=false",
      "-target=aws_cloudwatch_metric_alarm.security",
      `-out=.terraform/${planName}`,
    ])
    if (resultStatus(planResult) !== 0) return resultStatus(planResult)
    if (!fs.existsSync(planPath)) return fail("Terraform did not create the shared alarm plan")
    const plan = jsonResult(run, "terraform", [`-chdir=${accountSecurityDir}`, "show", "-json", `.terraform/${planName}`])
    if (!planIsScoped(plan, enabled, account)) return fail("shared alarm plan contains an unexpected change or identity")
    const metadata = { version: 1, account, enabled, planId, sha256: sha256(planPath, fs) }
    atomicWrite(metadataPath, `${JSON.stringify(metadata, null, 2)}\n`, fs)

    if (typeof options.beforeApply === "function") options.beforeApply({ planPath, metadataPath })
    const currentMetadata = fs.existsSync(metadataPath) ? readJsonFile(metadataPath, fs) : null
    if (
      !currentMetadata || currentMetadata.version !== 1 || currentMetadata.account !== account ||
      currentMetadata.enabled !== enabled || currentMetadata.planId !== planId ||
      !fs.existsSync(planPath) || currentMetadata.sha256 !== sha256(planPath, fs)
    ) return fail("shared alarm plan is missing, replaced, or owned by another operation")
    if (!verifyLock()) return fail("shared hosted operation lock ownership changed before apply")
    const revalidated = validateBackends(["accountSecurity", "staging", "production"], validationOptions)
    if (!revalidated.ok) return fail(revalidated.error)
    if (!enabled && !environmentStatesEmpty(run)) return fail("hosted environment state changed after shared alarm planning")

    applyStarted = true
    const applyResult = run("terraform", [`-chdir=${accountSecurityDir}`, "apply", `.terraform/${planName}`])
    if (resultStatus(applyResult) !== 0) return resultStatus(applyResult)

    const after = stateAddresses(run)
    if (!after || !alarmStateIsExpected(after)) return fail("shared alarm Terraform state is invalid after apply")
    const alarmAddresses = after.filter((address) => address.startsWith(alarmAddressPrefix)).sort()
    const expectedAddresses = enabled ? learningLabAlarmKeys.map(expectedAddress).sort() : []
    if (alarmAddresses.length !== expectedAddresses.length || alarmAddresses.some((address, index) => address !== expectedAddresses[index])) {
      return fail("shared alarm Terraform state does not match the durable lifecycle setting")
    }
    const region = plan.variables.aws_region.value
    if (!liveAlarmsMatch(run, region, enabled)) return fail("live learning-lab CloudWatch alarms do not match Terraform state")
    status = 0
    return 0
  } finally {
    fs.rmSync(planPath, { force: true })
    fs.rmSync(metadataPath, { force: true })
    fs.rmSync(overridePath, { force: true })
    if (status !== 0 && !applyStarted) writeSharedAlarmLifecycle(originalLifecycle, rootPath, fs)
  }
}
